  `/v1/pageindex/documents/${encodeURIComponent(documentId)}/versions/${encodeURIComponent(versionId)}/file`;

/** A physical page in the browser's PDF viewer (`#page=N`, 1-based). */
export const pageFragment = (page: number): string => `#page=${Math.max(1, Math.floor(page))}`;

export const pageSpan = (start: number, end: number): string =>
  end > start ? `pp. ${start}–${end}` : `p. ${start}`;

// ── answers ────────────────────────────────────────────────────────────────────────────────────

export type AnswerPart = { text: string } | { citation: number };

/**
 * The answer text cut at its citation markers: text runs and the index (into `citations`) of each
 * marker, so markers render as buttons. Markers the answer does not contain are left out.
 */
export function splitAnswer(
  answer: string,
  citations: readonly { marker: string }[],
): AnswerPart[] {
  const markers = citations
    .map((c, i) => ({ marker: c.marker, i }))
    .filter((m) => m.marker.length > 0)
    .sort((a, b) => b.marker.length - a.marker.length);
  const parts: AnswerPart[] = [];
  let run = "";
  let at = 0;
  while (at < answer.length) {
    const hit = markers.find((m) => answer.startsWith(m.marker, at));
    if (hit) {
      if (run) parts.push({ text: run });
      run = "";
      parts.push({ citation: hit.i });
      at += hit.marker.length;
    } else {
      run += answer[at];
      at += 1;
    }
  }
  if (run) parts.push({ text: run });
  return parts;
}
