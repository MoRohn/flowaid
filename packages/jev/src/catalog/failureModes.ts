/** Every catalog row a diagnostic code detects. */
export function failureModesForCode(code: JevDiagnosticCode): FailureMode[] {
  return FAILURE_MODES.filter((m) => m.static.includes(code));
}

/** Every catalog row a runtime route reason surfaces. */
export function failureModesForReason(reason: RouteReason): FailureMode[] {
  return FAILURE_MODES.filter((m) => m.runtime.includes(reason));
}

