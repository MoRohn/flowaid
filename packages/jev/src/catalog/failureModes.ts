/**
 * The failure-mode catalog as data (JEV_ENGINEERING.md §13.1, handbook §X, Table IX).
 *
 * Rows 1–12 are §X.A–§X.L; rows 13–31 are the warnings of other sections. "Static" are the
 * compiler/critic diagnostics, "runtime" the route reasons or receipt checks, "review" the
 * TraceReviewer signals, "inspectFirst" follows Table IX. Compiler diagnostics, runtime route
 * reasons, TraceReviewer signals and advisor rules all come from this one catalog (rule R10).
 */
import type { RouteReason } from "../wire.js";
import type { JevDiagnosticCode } from "./codes.js";

/** One failure mode. */
export interface FailureMode {
  /** 1..31 (§13.1 row number). */
  id: number;
  title: string;
  /** Handbook section, e.g. "§X.A". */
  handbook: string;
  /** Diagnostic codes that detect it statically. */
  static: readonly JevDiagnosticCode[];
  /** Prose for static detection that is not a code (by construction, schema, tests). */
  staticNote: string | null;
  /** Route reasons (or receipt checks) that surface it at run time. */
  runtime: readonly RouteReason[];
  runtimeNote: string | null;
  /** TraceReviewer signals / drift alarms. */
  review: readonly string[];
  /** Table IX "inspect first". */
  inspectFirst: readonly string[];
  correction: string;
}

const row = (
  id: number,
  title: string,
  handbook: string,
  staticCodes: readonly JevDiagnosticCode[],
  staticNote: string | null,
  runtime: readonly RouteReason[],
  runtimeNote: string | null,
  review: readonly string[],
  inspectFirst: readonly string[],
  correction: string,
): FailureMode =>
  Object.freeze({
    id,
    title,
    handbook,
    static: staticCodes,
    staticNote,
    runtime,
    runtimeNote,
    review,
    inspectFirst,
    correction,
  });

